function projectFilesByType(type, projectName, projectDir, requestText) {
    if (type === 'node-api') return makeNodeApiProject(projectName, projectDir);
    if (type === 'dashboard') return makeDashboardProject(projectName, projectDir, requestText);
    if (type === 'chat-app') return makeStaticWebProject(projectName, projectDir, requestText);
    return makeStaticWebProject(projectName, projectDir, requestText);
}

function spawnAsync(command, args, options = {}) {
    return new Promise((resolve) => {
        const child = spawn(command, args, { ...options, shell: false });
        let stdout = '';
        let stderr = '';
        child.stdout.on('data', (chunk) => { stdout += chunk.toString(); });
        child.stderr.on('data', (chunk) => { stderr += chunk.toString(); });
        child.on('close', (code) => resolve({ code: code ?? 1, stdout, stderr }));
        child.on('error', (error) => resolve({ code: 1, stdout, stderr: `${stderr}${error.message}` }));
    });
}

async function verifyProject(projectDir) {
    const checks = [];
    const files = [];
    const walk = (dir) => {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
            const fullPath = path.join(dir, entry.name);
            if (entry.isDirectory()) walk(fullPath);
            else files.push(fullPath);
        }
    };
    walk(projectDir);

    const jsFiles = files.filter((file) => file.endsWith('.js'));
    for (const file of jsFiles) {
        const result = await spawnAsync('node', ['--check', file], { cwd: projectDir });
        const ok = result.code === 0;
        checks.push({ file: path.relative(projectDir, file), check: 'node --check', ok, output: (result.stdout || result.stderr || '').slice(0, 400) });
    }

    const pyFiles = files.filter((file) => file.endsWith('.py'));
    for (const file of pyFiles) {
        const result = await spawnAsync('python', ['-m', 'py_compile', file], { cwd: projectDir });
        const ok = result.code === 0;
        checks.push({ file: path.relative(projectDir, file), check: 'py_compile', ok, output: (result.stdout || result.stderr || '').slice(0, 400) });
    }

    const htmlExists = files.some((file) => file.endsWith('.html'));
    checks.push({ file: 'index.html', check: 'presence', ok: htmlExists, output: htmlExists ? 'index.html found' : 'index.html missing' });

    return { ok: checks.every((item) => item.ok), checks };
}

export async function buildProjectFromRequest(query, ctx = {}) {
    const text = String(query || '').trim();
    if (!text) {
        return { status: 'blocked', reason: 'طلب البناء فارغ', project_name: null, directory: null };
    }
    if (!projectIntentRegex.test(text) || !projectTopicRegex.test(text)) {
        return { status: 'not_project_build', reason: 'هذا الطلب ليس طلب بناء مشروع', project_name: null, directory: null };
    }

    const rootDir = ctx.rootDir || process.cwd();
    const projectType = inferProjectType(text);
    const baseDir = baseBuiltProjectsDir(rootDir);
    fs.mkdirSync(baseDir, { recursive: true });

    const sourceName = extractProjectName(text).replace(/[\s\r\n]+/g, ' ').slice(0, 40);
    const projectName = slugify(sourceName || 'suras-project');
    const projectDir = path.join(baseDir, `${projectName}_${Date.now()}`);
    fs.mkdirSync(projectDir, { recursive: true });

    // Ollama 1.5b is more reliable when it generates one self-contained
    // document. Gemini keeps the richer multi-file generation path.
    let provider = String(process.env.AI_PROVIDER || '').trim().toLowerCase();
    if (!provider) {
        try {
            const envText = fs.readFileSync(path.join(__dirname, '..', '.env.env'), 'utf8');
            const match = envText.match(/^\s*AI_PROVIDER\s*=\s*([^\r\n#]+)/m);
            provider = match ? match[1].trim().replace(/^["']|["']$/g, '').toLowerCase() : 'ollama';
        } catch (_) {
            provider = 'ollama';
        }
    }

    // ─── Generate the primary HTML document ───
    const debugPath = path.join(baseDir, 'debug_cloudbridge.txt');
    let generatedFiles = [];

    const siteContext = `المستخدم طلب: "${text}"

قواعد التصميم:
1. إذا ذُكر موقع أو ماركة حقيقية (أمازون، نتفليكس، نايكي، آبل...) فأنشئ صفحة هبوط مستوحاة من هويتها البصرية فقط — لا تنسخ تصميمها الفعلي ولا هيكلها.
2. اخترع محتوى أصيلاً (منتجات، مزايا، تقييمات خيالية) ولا تستخدم بيانات الموقع الحقيقي.
3. استخدم نظام ألوان الماركة وخطوطها كمرجع بصري فقط.`;

    // ── 1. Generate self-contained HTML with Tailwind CDN ──
    const htmlPrompt = `${siteContext}

أنشئ ملف index.html كاملاً ومكتفياً بذاته تماماً. المتطلبات الإلزامية:
- أدرج Tailwind CSS عبر CDN في <head>: <script src="https://cdn.tailwindcss.com"></script>
- أدرج خط Google Fonts عربي في <head> (مثل Cairo أو Tajawal)
- جميع التنسيقات INLINE فقط (Tailwind classes + وسم <style> داخل الملف) — ممنوع منعاً باتاً أي <link rel="stylesheet"> لملف خارجي
- جميع JavaScript داخل وسم <script> في نهاية الملف — ممنوع منعاً باتاً أي <script src="..."> لملف خارجي
- استخدم صور placeholder شغّالة: https://picsum.photos/seed/KEYWORD/WIDTH/HEIGHT (استبدل KEYWORD بكلمة وصفية)
- اللغة العربية مع dir="rtl" و lang="ar"
- الأقسام المطلوبة: navbar + hero + مزايا (3 بطاقات) + شبكة منتجات (4-6 عناصر) + تقييمات عملاء + CTA + footer
- تصميم فاخر، حديث، ومتجاوب مع الجوال
- أخرج HTML خام فقط — بلا backticks ولا أي شرح.`;

    const htmlResp = await cloudBridge(htmlPrompt, '', 'code', 90000);

    // ── 2. Generate CSS (اختياري — تعزيز للتنسيقات الإضافية) ──
    const cssPrompt = `${siteContext}

أنشئ ملف styles.css اختيارياً لتعزيز التنسيقات:
- تأثيرات hover ناعمة وانتقالات سلسة
- متغيرات CSS لألوان الماركة
- استجابة كاملة مع media queries
- أخرج CSS خام فقط — بلا backticks ولا شرح.`;

    let cssResp = null;

    // ── 3. Generate JS (اختياري — تفاعلية إضافية) ──
    const jsPrompt = `${siteContext}

أنشئ ملف app.js اختيارياً لتفاعلية إضافية:
- سلوك navbar عند التمرير، قائمة متنقلة للجوال
- JavaScript خالص فقط — بلا مكتبات خارجية
- أخرج JS خام فقط — بلا backticks ولا شرح.`;

    let jsResp = null;
    if (provider === 'gemini') {
        cssResp = await cloudBridge(cssPrompt, '', 'code', 60000);
        jsResp = await cloudBridge(jsPrompt, '', 'code', 45000);
    }

    // ── Debug log ──
    fs.writeFileSync(debugPath, JSON.stringify({
        timestamp: new Date().toISOString(),
        query: text,
        htmlLen: htmlResp?.text?.length || 0,
        cssLen:  cssResp?.text?.length || 0,
        jsLen:   jsResp?.text?.length || 0,
        htmlPreview: htmlResp?.text?.slice(0, 300) || 'NULL',
        cssPreview:  cssResp?.text?.slice(0, 100) || 'NULL',
    }, null, 2));

    // ── Strip markdown fences if AI added them anyway ──
    function stripFence(code = '') {
        return code.trim()
            .replace(/^```[a-zA-Z]*\r?\n?/, '')
            .replace(/\r?\n?```$/, '')
            .trim();
    }

    // ── Repair truncated HTML so it always renders ──
    function repairHtml(html = '') {
        html = html.trim();
        if (!html) return html;

        // ✅ تأكد أن Tailwind CDN موجود دائماً
        if (!html.includes('tailwindcss') && !html.includes('tailwind.min.css')) {
            const tw = '<script src="https://cdn.tailwindcss.com"></script>';
            html = html.includes('</head>')
                ? html.replace('</head>', `${tw}\n</head>`)
                : tw + '\n' + html;
        }

        // ✅ أزل روابط الملفات الخارجية (styles.css / app.js) حتى لا تظهر أخطاء 404
        // الصفحة مكتفية ذاتياً بـ Tailwind + inline styles/scripts
        html = html.replace(/<link[^>]+rel=["']stylesheet["'][^>]+href=["'][^"']*styles\.css["'][^>]*\/?>/gi, '');
        html = html.replace(/<script[^>]+src=["'][^"']*app\.js["'][^>]*><\/script>/gi, '');

        // ✅ أغلق HTML المبتور
        if (!html.includes('</body>')) html += '\n</body>';
        if (!html.includes('</html>')) html += '\n</html>';
        return html;
    }

    if (htmlResp?.text) {
        const html = repairHtml(stripFence(htmlResp.text));
        writeFileSafe(path.join(projectDir, 'index.html'), html);
        generatedFiles.push(path.join(projectDir, 'index.html'));
    }
    if (cssResp?.text) {
        writeFileSafe(path.join(projectDir, 'styles.css'), stripFence(cssResp.text));
        generatedFiles.push(path.join(projectDir, 'styles.css'));
    }
    if (jsResp?.text) {
        writeFileSafe(path.join(projectDir, 'app.js'), stripFence(jsResp.text));
        generatedFiles.push(path.join(projectDir, 'app.js'));
    }

    if (generatedFiles.length === 0) {
        fs.appendFileSync(debugPath, '\n\nFALLING BACK TO HARDCODED!');
        generatedFiles = projectFilesByType(projectType, projectName, projectDir, text);
    } else {
        fs.appendFileSync(debugPath, `\n\nSUCCESS: ${generatedFiles.length} files written`);
    }
    
    const verification = await verifyProject(projectDir);
    const previewPath = path.join(projectDir, 'index.html');
    const previewUrl = fs.existsSync(previewPath)
        ? `http://localhost:3001/preview-file?path=${encodeURIComponent(previewPath)}`
        : null;

    return {
        status: 'ok',
        project_name: projectName,
        project_type: projectType,
        directory: projectDir,
        generated_files: generatedFiles,
        verification,
        preview_url: previewUrl,
        stages: [
            'analyze_request',
            'plan_project',
            'generate_files',
            'verify_project',
            'report_results',
        ],
    };
}

