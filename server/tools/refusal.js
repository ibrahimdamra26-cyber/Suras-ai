// سياقات بريئة تُعفي من الرفض: حماية/شرح/توعية/قانون
const EXEMPT_RE = /(احم|حماية|حمايه|دفاع|دافع|اشرح|شرح|ما هو|ما هي|عرفني على|توعية|قانون|عقوبة|كيف أحمي|كيف احمي|أخلاق|تعريف|مفهوم|مفاهيم|راجع كودي|افحص كودي|موقعي الخاص|مشروعي الخاص)/i;

/**
 * @returns {{ id, redirect } | null}
 */
export function checkHarmful(query) {
    const text = String(query || '');
    if (EXEMPT_RE.test(text)) return null;
    for (const h of HARMFUL) {
        if (h.re.test(text)) return { id: h.id, redirect: h.redirect };
    }
    return null;
}

