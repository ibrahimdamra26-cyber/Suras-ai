// وضع الاختبار (Test Mode) — للاختبار الأحمر فقط.
// يُفتح ويُغلق بأمر صريح، والحماية تبقى في الكود لا تُحذف.
// عند الفتح: تُسجَّل النوايا المؤذية (قابلة للمراقبة) لكن تُمرَّر.
// ============================================================
let _testModeOpen = false;

export function isRefusalTestMode() {
    return _testModeOpen;
}

export function setRefusalTestMode(open) {
    _testModeOpen = !!open;
    console.log(`[Safety] وضع اختبار الحدود: ${_testModeOpen ? 'مفتوح 🔓' : 'مغلق 🔒'}`);
    return _testModeOpen;
}

/** محظور فعلاً؟ (مؤذٍ + وضع الاختبار مغلق) */
export function isHarmfulBlocked(query) {
    if (_testModeOpen) return null;
    return checkHarmful(query);
}

const TEST_OPEN_RE = /(افتح|فعّل|فعل|شغّل|شغل|ابدا|ابدأ).*(وضع الاختبار|اختبار الحدود|الاختبار الأمني)|وضع الاختبار.*(افتح|شغل)/i;
const TEST_CLOSE_RE = /(عطّل|عطل|أغلق|اغلق|انه|أنه|أنهِ|أوقف|اوقف|سكّر|اقفل).*(وضع الاختبار|الاختبار)|انهاء الاختبار|إنهاء الاختبار/i;

/** أوامر التحكم بوضع الاختبار عبر الشات. @returns {'open'|'close'|null} */
export function matchTestCommand(query) {
    const text = String(query || '');
    if (TEST_CLOSE_RE.test(text)) return 'close';
    if (TEST_OPEN_RE.test(text)) return 'open';
    return null;
}
