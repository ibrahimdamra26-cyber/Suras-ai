const DIALECT_MAP = new Map();
for (const k of Object.keys(RAW_MAP)) {
    DIALECT_MAP.set(baseNorm(k), RAW_MAP[k]);
}
for (const k of Object.keys(FAMILY_RAW)) {
    DIALECT_MAP.set(baseNorm(k), FAMILY_RAW[k]);
}

const SPLIT_RE = /[\s_.,،؛؟?!.|/\\\-:"'()\[\]{}]+/;

/** الصيغة المعتمدة لرمز واحد، أو null إن لم يكن لهجياً. */
export function canonicalToken(tok) {
    const n = baseNorm(tok);
    return DIALECT_MAP.get(n) || null;
}

/**
 * توسيع النص بإلحاق المرادفات الفصيحة للرموز اللهجية المكتشفة.
 * النص الأصلي محفوظ كاملاً أولاً — الإضافة فقط بعده.
 */
export function expandWithDialects(text) {
    const s = String(text || '');
    if (!s) return s;
    const toks = s.split(SPLIT_RE).filter(t => t.length > 0);
    const have = new Set(toks.map(baseNorm));
    const add = [];
    for (const t of toks) {
        const c = canonicalToken(t);
        if (c && !have.has(baseNorm(c))) {
            have.add(baseNorm(c));
            add.push(c);
        }
    }
    return add.length ? s + ' ' + add.join(' ') : s;
}

/** هل يحتوي النص أي رمز لهجي معروف؟ (تشخيص) */
export function hasDialect(text) {
    const toks = String(text || '').split(SPLIT_RE);
    return toks.some(t => DIALECT_MAP.has(baseNorm(t)));
}
