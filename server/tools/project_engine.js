const projectIntentRegex = /(أنشئ|أنشأ|اصنع|أنشِئ|ابني|أبني|بني|صمم|تصميم|معمارية|build|create|generate|scaffold|make|مشروع|project|تطبيق|واجهة|موقع|website|dashboard|api)/i;
const projectTopicRegex = /(مشروع|project|موقع|website|واجهة|ui|dashboard|app|تطبيق|api|backend|bot|landing|صفحة|site|هيكل|ملفات|مجلدات)/i;

function slugify(value) {
    return String(value || 'suras-project')
        .toLowerCase()
        .trim()
        .replace(/[^a-z0-9\u0600-\u06FF\s-]+/g, '')
        .replace(/[\s_]+/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '')
        .slice(0, 40) || 'suras-project';
}

function hashText(value) {
    let hash = 2166136261;
    for (const char of String(value || '')) {
        hash ^= char.codePointAt(0);
        hash = Math.imul(hash, 16777619);
    }
    return Math.abs(hash >>> 0);
}

function extractProjectName(query) {
    const cleaned = String(query || '')
        .replace(/(?:اريد|أريد|ابغى|أبغى|بدي|عايز|عاوز|احتاج|أحتاج|من فضلك|لو سمحت)/gi, ' ')
        .replace(/(?:انشئ|أنشئ|اصنع|ابني|أبني|بني|صمم|تصميم|اعمل|سوي|سويلي|لي|لنا|مشروع|project|build|create|generate|make)/gi, ' ')
        .replace(/\s+/g, ' ')
        .trim();
    return cleaned || 'suras-project';
}

function baseBuiltProjectsDir(rootDir = process.cwd()) {
    return path.join(path.resolve(rootDir, '..'), 'built_projects');
}

function inferProjectType(query) {
    const text = String(query || '').toLowerCase();
    if (/(api|backend|server|express|rest|endpoint)/i.test(text)) return 'node-api';
    if (/(dashboard|لوحة|admin|panel)/i.test(text)) return 'dashboard';
    if (/(bot|assistant|chat|conversation)/i.test(text)) return 'chat-app';
    return 'static-web';
}

function writeFileSafe(filePath, content) {
    const dir = path.dirname(filePath);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(filePath, content, 'utf-8');
}

